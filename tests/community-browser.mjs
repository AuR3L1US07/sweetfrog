import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
const base = process.env.COMMUNITY_TEST_URL || 'http://127.0.0.1:4175/';
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 850 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '#suggestions');
  await page.locator('.club-heading h1').getByText('意见留言').waitFor();
  assert.match(await page.locator('.club-gate').textContent(), /游客可以浏览/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.goto(base + '#account');
  await page.getByRole('button', { name: '注册', exact: true }).click();
  const username = 'frog' + Math.floor(Math.random() * 100000000);
  await page.locator('[name=username]').fill(username);
  await page.locator('[name=password]').fill('testpassword123');
  await page.getByRole('button', { name: '创建账号 ↗' }).click();
  await page.waitForURL('**/#games');
  await page.goto(base + '#suggestions');
  const suggestionTitle = '测试提议' + username;
  await page.locator('.club-form [name=title]').fill(suggestionTitle);
  await page.locator('.club-form [name=body]').fill('可以加一个倒计时提示。');
  await page.getByRole('button', { name: '发布提议 ↗' }).click();
  await page.getByRole('heading', { name: suggestionTitle }).waitFor();
  const card = page.locator('.club-card').filter({ hasText: suggestionTitle });
  await card.locator('.vote-button').click();
  await page.waitForFunction(() => { const c = [...document.querySelectorAll('.club-card')].find(x => x.textContent.includes('测试提议')); return c?.querySelector('.vote-button')?.disabled; });
  assert.match(await card.locator('.vote-button').textContent(), /1/);
  await page.goto(base + '#discussion');
  const topicTitle = '测试话题' + username;
  await page.locator('.club-form [name=title]').fill(topicTitle);
  await page.locator('.club-form [name=body]').fill('大家最喜欢哪个游戏？');
  await page.getByRole('button', { name: '发布话题 ↗' }).click();
  await page.getByRole('heading', { name: topicTitle }).waitFor();
  const topic = page.locator('.topic-card').filter({ hasText: topicTitle });
  await topic.locator('.club-text-button').click();
  await topic.locator('.club-reply-form textarea').fill('我喜欢青蛙2048。');
  await topic.getByRole('button', { name: '发送回复' }).click();
  await topic.getByText('我喜欢青蛙2048。').waitFor();
  await page.goto(base + '#leaderboard');
  assert.equal(await page.locator('.club-tab').count(), 5);
  await page.goto(base + '#account');
  await page.getByRole('button', { name: '退出登录' }).click();
  await page.goto(base + '#leaderboard');
  assert.match(await page.locator('.club-my-rank').textContent(), /游客可以看榜/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  await page.close();
  console.log('PASS: guest browsing, registration, suggestions, unique vote, discussion, reply and responsive leaderboard');
} finally { await browser.close(); }
